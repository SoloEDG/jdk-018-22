function inRanges(cp: number, ranges: ReadonlyArray<readonly [number, number]>) {
  let lo = 0;
  let hi = ranges.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [start, end] = ranges[mid]!;
    if (cp < start) hi = mid - 1;
    else if (cp > end) lo = mid + 1;
    else return true;
  }
  return false;
}

export function isControlCodePoint(cp: number): boolean {
  return cp < 0x20 || (cp >= 0x7f && cp <= 0x9f);
}

export function isZeroWidthCodePoint(cp: number): boolean {
  if (isControlCodePoint(cp)) return true;
  if (cp === 0x00ad) return false;
  if (cp === 0x200b || cp === 0x200c || cp === 0x200d) return true;
  if (cp === 0x2060 || cp === 0xfeff || cp === 0x180e) return true;
  if (cp >= 0xfe00 && cp <= 0xfe0f) return true;
  if (cp >= 0xe0100 && cp <= 0xe01ef) return true;
  if (cp >= 0x1160 && cp <= 0x11ff) return true;
  if (cp >= 0x1f3fb && cp <= 0x1f3ff) return true;
  if (cp >= 0xe0020 && cp <= 0xe007f) return true;
  const ch = String.fromCodePoint(cp);
  return /[\p{Mn}\p{Me}\p{Cf}]/u.test(ch);
}

export function isWideCodePoint(cp: number): boolean {
  return inRanges(cp, WIDE);
}

export function isAmbiguousCodePoint(cp: number): boolean {
  return inRanges(cp, AMBIGUOUS);
}

export function isRegionalIndicator(cp: number): boolean {
  return cp >= 0x1f1e6 && cp <= 0x1f1ff;
}
